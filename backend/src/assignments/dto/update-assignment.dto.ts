import { IsArray, IsOptional, IsUUID } from 'class-validator';

/**
 * Оноосон даалгаврын **хүрээг засах**.
 *
 * Хоёр бодит хэрэгцээ:
 *  - даалгавар өгсний **дараа шинэ сурагч** ангид элсэх,
 *  - буруу сурагч сонгосныг залруулах.
 *
 * Урьд нь ганц ч зам байгаагүй тул багш даалгавраа устгаад дахин өгөхөөс өөр
 * аргагүй байв — тэгэхэд аль хэдийн хийсэн сурагчдын дүн бүгд алга болно.
 */
export class UpdateAssignmentDto {
  /**
   * Хэнд оногдох вэ. **Хоосон массив = бүх анги** (`create`-тэй ижил дүрэм:
   * өгөөгүй нь бүх анги гэсэн үг).
   *
   * Шинээр нэмэгдсэн сурагчид гүйцэтгэлийн мөр үүснэ; хасагдсан сурагчийн
   * мөр нь **зөвхөн хийгээгүй бол** устна — дүнг нь хэзээ ч устгахгүй.
   */
  @IsOptional()
  @IsArray()
  @IsUUID('4', { each: true })
  studentIds?: string[];
}
